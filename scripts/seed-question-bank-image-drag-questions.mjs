function parseArgs(argv) {
  const args = { dbPath: null, dryRun: false, outPath: null }
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i]
    if (token === '--db') {
      args.dbPath = argv[++i]
      continue
    }
    if (token === '--dry-run') {
      args.dryRun = true
      continue
    }
    if (token === '--out') {
      args.outPath = argv[++i]
      continue
    }
    throw new Error(`[drag-question-seed] unknown arg: ${token}`)
  }
  return args
}

