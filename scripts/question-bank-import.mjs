#!/usr/bin/env node
// 专业岗位题库（298条）v0.1.10 → v0.1.12 重导脚本。
// 依据：doc/specs/impl/04-question-bank-import-cleaning-spec.md §7 导入执行顺序。
//
// 用法：
//   node scripts/question-bank-import.mjs --dry-run
//   node scripts/question-bank-import.mjs --db <path>
//
// dry-run 模式只输出 §6 报告到 stdout，不写库、不生成 SQL 文件。
// 正式模式生成 SQL 到 doc/features/question-bank-import.sql 并通过 sqlite3 CLI 执行
//（与 seed-question-bank-source.mjs 同构，AGENTS.md 一次性数据运维约束）。

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { homedir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { mapImportRow, buildQuestionBankImportSql, buildQuestionImportedEventsSql, buildDryRunReport } from './lib/question-bank-import.mjs'
import { resolveDefaultDbPath } from './lib/database-path.mjs'

function parseArgs(argv) {
  const args = { dbPath: null, outPath: null, dryRun: false, sourcePath: null }
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i]
    if (token === '--db') {
      args.dbPath = argv[++i]
      continue
    }
    if (token === '--out') {
      args.outPath = argv[++i]
      continue
    }
    if (token === '--source') {
      args.sourcePath = argv[++i]
      continue
    }
    if (token === '--dry-run') {
      args.dryRun = true
      continue
    }
    throw new Error(`[question-bank-import] unknown arg: ${token}`)
  }
  return args
}

const projectRoot = fileURLToPath(new URL('..', import.meta.url))
const pkg = JSON.parse(readFileSync(join(projectRoot, 'package.json'), 'utf-8'))
const appName = pkg.name
const args = parseArgs(process.argv.slice(2))

const sourcePath =
  args.sourcePath ?? join(projectRoot, 'doc', 'reference', '专业岗位能力测评题库-M1-M6-数据库导出-298条.json')
const dbPath = args.dbPath ?? resolveDefaultDbPath({ platform: process.platform, homeDir: homedir(), appName })
const outPath = args.outPath ?? join(projectRoot, 'doc', 'features', 'question-bank-import.sql')

const rawRows = JSON.parse(readFileSync(sourcePath, 'utf-8'))
console.log(`[question-bank-import] loaded ${rawRows.length} rows from ${sourcePath}`)

const importedRows = []
const errors = []
for (const rawRow of rawRows) {
  try {
    importedRows.push(mapImportRow(rawRow))
  } catch (err) {
    errors.push({ question_id: rawRow.question_id, message: err.message })
  }
}

if (errors.length > 0) {
  console.error(`[question-bank-import] ${errors.length} row(s) failed to import:`)
  for (const e of errors) {
    console.error(`  ${e.question_id}: ${e.message}`)
  }
  process.exit(1)
}

console.log(`[question-bank-import] mapped ${importedRows.length} rows successfully`)

if (args.dryRun) {
  const report = buildDryRunReport(importedRows)
  console.log('\n=== dry-run report ===')
  console.log(JSON.stringify(report, null, 2))

  if (report.reconciliation_grand_total !== rawRows.length) {
    console.error(
      `[question-bank-import] [WARN] reconciliation grand total (${report.reconciliation_grand_total}) != source row count (${rawRows.length})`
    )
  }
  if (!report.domain_isolation.pass) {
    console.error('[question-bank-import] [FAIL] domain isolation check failed')
    process.exit(1)
  }
  console.log('\n[question-bank-import] dry-run only; no rows written.')
  process.exit(0)
}

const importBatchId = `batch_reimport_v012_${new Date().toISOString().replace(/[-:TZ.]/g, '').slice(0, 14)}`
const importedAt = new Date().toISOString()

const sql = [
  '-- Generated by scripts/question-bank-import.mjs',
  `-- Source: ${sourcePath}`,
  `-- Import batch: ${importBatchId}`,
  `-- Generated at: ${importedAt}`,
  '-- [!] Imported rows are DRAFT. Activation requires the T5 human review gate',
  '--     (doc/specs/impl/07-implementation-task-book.md §T5), not a bulk UPDATE.',
  'BEGIN;',
  '-- v0.1.12 全量重导前先清空旧 JOB_SPECIFIC 题（前置人工检查：确认无 session 引用，见 00-START-HERE.md §3.1）',
  "DELETE FROM question_bank WHERE bank_domain = 'JOB_SPECIFIC';",
  buildQuestionBankImportSql(importedRows),
  buildQuestionImportedEventsSql(importedRows, { importBatchId, importedAt, actorId: 'system_import' }),
  'COMMIT;'
].join('\n')

writeFileSync(outPath, sql + '\n', 'utf-8')
console.log(`[question-bank-import] SQL written to ${outPath}`)

if (!existsSync(dbPath)) {
  console.error(`[question-bank-import] DB file not found: ${dbPath}`)
  console.error('[question-bank-import] 请先运行 npm run dev 初始化 Electron DB，或通过 --db 指定现有 DB。')
  process.exit(1)
}

try {
  execFileSync('sqlite3', [dbPath], { input: sql, stdio: ['pipe', 'inherit', 'inherit'] })
} catch (err) {
  if (err && err.code === 'ENOENT') {
    console.error('[question-bank-import] sqlite3 CLI not found. Please install sqlite3 first.')
  } else {
    console.error(`[question-bank-import] sqlite3 execution failed: ${err.message}`)
  }
  process.exit(1)
}

console.log(`[question-bank-import] imported ${importedRows.length} DRAFT rows into ${dbPath}`)
