#!/usr/bin/env node
/**
 * 校验 doc/assets/asset-manifest.json，并将其中 approved 资产投影到 asset_resource。
 * planned/generated/reviewing/retired 资产永远不会写成 ACTIVE。
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  approvedAssetsToResourceRows,
  buildVisualAssetResourceSql,
  validateVisualAssetManifest
} from './lib/visual-asset-manifest.mjs'
import { resolveDefaultDbPath } from './lib/database-path.mjs'
import { executeSqliteScript } from './lib/sqlite-cli.mjs'

function parseArgs(argv) {
  const args = { dryRun: false, dbPath: null, outPath: null }
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i]
    if (token === '--dry-run') { args.dryRun = true; continue }
    if (token === '--db') { args.dbPath = argv[++i]; continue }
    if (token === '--out') { args.outPath = argv[++i]; continue }
    throw new Error(`[asset-seed] unknown arg: ${token}`)
  }
  return args
}

const projectRoot = fileURLToPath(new URL('..', import.meta.url))
const manifestPath = join(projectRoot, 'doc', 'assets', 'asset-manifest.json')
const pkg = JSON.parse(readFileSync(join(projectRoot, 'package.json'), 'utf8'))
const args = parseArgs(process.argv.slice(2))
const dbPath = args.dbPath ?? resolveDefaultDbPath({
  platform: process.platform,
  homeDir: homedir(),
  appName: pkg.name
})
const outPath = args.outPath ?? join(tmpdir(), `${pkg.name}-visual-asset-seed.sql`)
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
const validation = validateVisualAssetManifest(manifest, { projectRoot })

if (!validation.ok) {
  for (const error of validation.errors) console.error(`[asset-seed] ${error}`)
  process.exit(1)
}

const rows = approvedAssetsToResourceRows(manifest, projectRoot)
const timestamp = new Date().toISOString()
const sql = [
  '-- Generated by scripts/seed-question-bank-image-assets.mjs',
  `-- Source: ${manifestPath}`,
  `-- Generated at: ${timestamp}`,
  '-- Only lifecycle_status=approved assets are projected as ACTIVE.',
  buildVisualAssetResourceSql(rows, timestamp)
].join('\n')
writeFileSync(outPath, `${sql}\n`, 'utf8')

if (args.dryRun) {
  console.log(`[asset-seed] dry run: approved=${rows.length}, sql=${outPath}`)
  process.exit(0)
}

if (rows.length === 0) {
  console.error('[asset-seed] manifest contains no approved assets; database was not changed')
  process.exit(1)
}
if (!existsSync(dbPath)) {
  console.error(`[asset-seed] DB file not found: ${dbPath}`)
  process.exit(1)
}

executeSqliteScript(dbPath, sql, { stdio: ['ignore', 'inherit', 'inherit'] })
console.log(`[asset-seed] projected ${rows.length} approved assets into ${dbPath}`)
