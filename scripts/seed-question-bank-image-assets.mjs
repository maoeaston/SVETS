#!/usr/bin/env node
/**
 * 将 doc/features/question-bank-image-asset-seed-input.tsv 落入 asset_resource。
 *
 * 用法：
 *   node scripts/seed-question-bank-image-assets.mjs
 *   node scripts/seed-question-bank-image-assets.mjs --dry-run
 *   node scripts/seed-question-bank-image-assets.mjs --db /abs/path/to/xc-career-guide.db
 *   node scripts/seed-question-bank-image-assets.mjs --out /tmp/asset_resource.sql
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { homedir } from 'node:os'
import { fileURLToPath } from 'node:url'
import {
  buildAssetResourceUpsertSql,
  parseAssetSeedTsv,
  resolveDefaultDbPath,
  validateAssetSeedRows
} from './lib/question-bank-image-asset-seed.mjs'

function parseArgs(argv) {
  const args = { dryRun: false, dbPath: null, outPath: null }
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i]
    if (token === '--dry-run') {
      args.dryRun = true
      continue
    }
    if (token === '--db') {
      args.dbPath = argv[++i]
      continue
    }
    if (token === '--out') {
      args.outPath = argv[++i]
      continue
    }
    throw new Error(`[asset-seed] unknown arg: ${token}`)
  }
  return args
}

const projectRoot = fileURLToPath(new URL('..', import.meta.url))
const pkg = JSON.parse(readFileSync(join(projectRoot, 'package.json'), 'utf-8'))
const appName = pkg.name
const tsvPath = join(projectRoot, 'doc', 'features', 'question-bank-image-asset-seed-input.tsv')
const defaultOutPath = join(projectRoot, 'doc', 'features', 'question-bank-image-asset-resource-seed.sql')

const args = parseArgs(process.argv.slice(2))
const dbPath =
  args.dbPath ??
  resolveDefaultDbPath({
    platform: process.platform,
    homeDir: homedir(),
    appName
  })

const tsvText = readFileSync(tsvPath, 'utf-8')
const rows = parseAssetSeedTsv(tsvText)
validateAssetSeedRows(rows)

const isoTimestamp = new Date().toISOString()
const sql = [
  '-- Generated by scripts/seed-question-bank-image-assets.mjs',
  `-- Source: ${tsvPath}`,
  `-- Generated at: ${isoTimestamp}`,
  '-- [!] DRG-OBJ02 overview pack remains placeholder_only; only split child assets may be treated as drag_items asset.',
  buildAssetResourceUpsertSql(rows, isoTimestamp)
].join('\n')

writeFileSync(args.outPath ?? defaultOutPath, sql + '\n', 'utf-8')

if (args.dryRun) {
  console.log(`[asset-seed] dry run only; SQL written to ${args.outPath ?? defaultOutPath}`)
  console.log(`[asset-seed] target DB would be: ${dbPath}`)
  process.exit(0)
}

if (!existsSync(dbPath)) {
  console.error(`[asset-seed] DB file not found: ${dbPath}`)
  console.error('[asset-seed] 请先运行 npm run dev 一次初始化 Electron DB，或通过 --db 指定现有 DB。')
  process.exit(1)
}

try {
  execFileSync('sqlite3', [dbPath], {
    input: sql,
    stdio: ['pipe', 'inherit', 'inherit']
  })
} catch (err) {
  if (err && err.code === 'ENOENT') {
    console.error('[asset-seed] sqlite3 CLI not found. Please install sqlite3 first.')
  } else {
    console.error(`[asset-seed] sqlite3 execution failed: ${err.message}`)
  }
  process.exit(1)
}

const verifySql = `
SELECT asset_id, app_uri, status
FROM asset_resource
WHERE asset_id IN (
  'asset_img_jdg_ms02_shelf_master_v001',
  'asset_img_jdg_ms02_facing_correct_v001',
  'asset_img_jdg_ms02_facing_wrong_v001',
  'asset_img_jdg_ms04_safety_master_v001',
  'asset_img_drg_bg01_shelf_board_v001',
  'asset_img_drg_obj02_goods_pack_v003',
  'asset_img_drg_obj02_snack_box_blue_v002',
  'asset_img_drg_obj02_snack_box_red_v002',
  'asset_img_drg_obj02_snack_box_yellow_v002',
  'asset_img_drg_obj02_snack_box_green_v002'
)
ORDER BY asset_id;
`

const verifyOutput = execFileSync('sqlite3', [dbPath, verifySql], { encoding: 'utf-8' })
console.log(`[asset-seed] seeded asset_resource into ${dbPath}`)
console.log(verifyOutput.trimEnd())
