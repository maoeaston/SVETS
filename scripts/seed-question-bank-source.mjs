#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { homedir } from 'node:os'
import { fileURLToPath } from 'node:url'
import {
  buildQuestionBankDraftUpsertSql,
  mapSourceRow,
  parseCsv,
  summarizeQuestionRows
} from './lib/question-bank-source-seed.mjs'
import { resolveDefaultDbPath } from './lib/database-path.mjs'
import { executeSqliteScript } from './lib/sqlite-cli.mjs'

function parseArgs(argv) {
  const args = { csvPath: null, dbPath: null, outPath: null, dryRun: false, importedBy: 'codex' }

  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i]
    if (token === '--csv') {
      args.csvPath = argv[++i]
      continue
    }
    if (token === '--db') {
      args.dbPath = argv[++i]
      continue
    }
    if (token === '--out') {
      args.outPath = argv[++i]
      continue
    }
    if (token === '--imported-by') {
      args.importedBy = argv[++i]
      continue
    }
    if (token === '--dry-run') {
      args.dryRun = true
      continue
    }
    throw new Error(`[question-bank-source-seed] unknown arg: ${token}`)
  }

  if (!args.csvPath) {
    throw new Error('[question-bank-source-seed] --csv is required')
  }

  return args
}

const projectRoot = fileURLToPath(new URL('..', import.meta.url))
const pkg = JSON.parse(readFileSync(join(projectRoot, 'package.json'), 'utf-8'))
const appName = pkg.name
const args = parseArgs(process.argv.slice(2))
const dbPath =
  args.dbPath ??
  resolveDefaultDbPath({
    platform: process.platform,
    homeDir: homedir(),
    appName
  })
const outPath =
  args.outPath ?? join(projectRoot, 'doc', 'features', 'question-bank-source-seed.sql')
const importBatchId = `batch_${new Date().toISOString().replace(/[-:TZ.]/g, '').slice(0, 14)}`
const importedAt = new Date().toISOString()
const counters = new Map()

const csvText = readFileSync(args.csvPath, 'utf-8')
const sourceRows = parseCsv(csvText)
const questionRows = sourceRows.map((row, index) =>
  mapSourceRow(row, {
    jobCode: 'SUPERMARKET_SHELVER',
    importBatchId,
    sourceFile: basename(args.csvPath),
    importedAt,
    importedBy: args.importedBy,
    counters,
    sourceRow: index + 2
  })
)

const summary = summarizeQuestionRows(questionRows)
const sql = [
  '-- Generated by scripts/seed-question-bank-source.mjs',
  `-- Source: ${args.csvPath}`,
  `-- Import batch: ${importBatchId}`,
  `-- Generated at: ${importedAt}`,
  '-- [!] Imported rows are DRAFT placeholders. Review gate must block activation until answers/options/drag structure are completed.',
  'BEGIN;',
  buildQuestionBankDraftUpsertSql(questionRows),
  'COMMIT;'
].join('\n')

writeFileSync(outPath, sql + '\n', 'utf-8')

console.log(
  `[question-bank-source-seed] prepared ${summary.total} DRAFT rows (${Object.entries(summary.byModule)
    .map(([moduleType, count]) => `${moduleType}:${count}`)
    .join(', ')})`
)
console.log(`[question-bank-source-seed] SQL written to ${outPath}`)

if (args.dryRun) {
  console.log(`[question-bank-source-seed] dry run only; target DB would be: ${dbPath}`)
  process.exit(0)
}

if (!existsSync(dbPath)) {
  console.error(`[question-bank-source-seed] DB file not found: ${dbPath}`)
  console.error('[question-bank-source-seed] 请先运行 npm run dev 初始化 Electron DB，或通过 --db 指定现有 DB。')
  process.exit(1)
}

try {
  executeSqliteScript(dbPath, sql, { stdio: ['ignore', 'inherit', 'inherit'] })
} catch (err) {
  if (err && err.code === 'ENOENT') {
    console.error('[question-bank-source-seed] sqlite3 CLI not found. Please install sqlite3 first.')
  } else {
    console.error(`[question-bank-source-seed] sqlite3 execution failed: ${err.message}`)
  }
  process.exit(1)
}

console.log(`[question-bank-source-seed] seeded question_bank into ${dbPath}`)
